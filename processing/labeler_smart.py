"""Smart label generation from mesh object properties.

Generates descriptive, natural-language labels that match what a user
would type as a text prompt.  The goal is: if someone typed this label
into the mesh generator, the output should look like this mesh.

Priority order (best→worst):
1. Objaverse metadata (name + tags) — richest source
2. Object name from Blender (often descriptive: 'Face', 'Sword_blade')
3. File-level label combined with object context
4. Material names (tell us what the object looks like)
5. Geometry analysis (aspect ratio, complexity)

Label quality rules:
- NEVER include numeric IDs, hex hashes, version strings
- NEVER include project/scene names ('blender 3.3 splash', 'iron man blender swap')
- NEVER include Blender internal prefixes (GEO-, HLP-, DP-, etc.)
- Keep labels 2-8 words, natural, lowercase
- Labels should read like user prompts: 'car wheel', 'wooden table leg'
- Foreign words are translated via a JSON cache generated by scripts/translate_labels.py
"""

import json
import re
from pathlib import Path

import numpy as np


def compute_bbox_aspect(vertices):
    """Compute bounding box extents from vertices.

    Returns (width, depth, height) tuple or None on failure.
    """
    if not vertices or len(vertices) < 3:
        return None
    verts = np.array(vertices)
    if not np.all(np.isfinite(verts)):
        return None
    mins = verts.min(axis=0)
    maxs = verts.max(axis=0)
    extents = maxs - mins
    return tuple(extents.tolist())


# ── Translation cache (generated by scripts/translate_labels.py via Qwen) ──
_TRANSLATIONS_PATH = Path(__file__).resolve().parent.parent / "data" / "label_translations.json"
_TRANSLATION_CACHE: dict[str, str] = {}

def _load_translation_cache():
    """Load Qwen-generated translations from JSON cache."""
    global _TRANSLATION_CACHE
    if _TRANSLATIONS_PATH.exists():
        try:
            _TRANSLATION_CACHE = json.loads(_TRANSLATIONS_PATH.read_text())
        except Exception:
            _TRANSLATION_CACHE = {}

_load_translation_cache()

# Compile a regex for cached translation replacement (whole words only)
def _build_translation_re():
    if not _TRANSLATION_CACHE:
        return None
    return re.compile(
        r'\b(' + '|'.join(
            re.escape(k) for k in sorted(_TRANSLATION_CACHE, key=len, reverse=True)
        ) + r')\b',
        re.IGNORECASE,
    )

_TRANSLATION_RE = _build_translation_re()


def _translate_foreign(text):
    """Replace known foreign words with English equivalents from cache."""
    if not _TRANSLATION_RE or not _TRANSLATION_CACHE:
        return text
    def _repl(m):
        return _TRANSLATION_CACHE.get(m.group(0).lower(), m.group(0))
    return _TRANSLATION_RE.sub(_repl, text)


# ── Cleaning helpers ──────────────────────────────────────────────────

def _strip_numeric_ids(text):
    """Remove BlendSwap-style numeric ID prefixes and 'popular' marker."""
    text = re.sub(r'^\d+\s+popular\b[,\s]*', '', text)
    text = re.sub(r'^\d+[_\s]+', '', text)
    return text.strip()


def _strip_blender_prefixes(text):
    """Remove Blender internal prefixes (GEO-, HLP-, etc.)."""
    prefixes = ['geo ', 'geo-', 'hlp ', 'hlp-', 'dp ', 'dp-',
                'grp ', 'grp-', 'rig ', 'rig-', 'ctrl ', 'ctrl-',
                'def ', 'def-', 'mch ', 'mch-', 'org ', 'org-',
                'wgt ', 'wgt-', 'emt ', 'emt-']
    lower = text.lower()
    for p in prefixes:
        if lower.startswith(p):
            text = text[len(p):]
            lower = text.lower()
    return text.strip()


def _strip_hex_uids(text):
    """Remove hex UIDs (Objaverse-style 32-char hashes)."""
    text = re.sub(r'\b[0-9a-f]{8,}\b', '', text)
    return re.sub(r'\s+', ' ', text).strip()


def _strip_encoding_artifacts(text):
    """Remove encoding artifacts like ⁇ and escaped chars."""
    text = text.replace('\u2047', '')
    text = re.sub(r'\\x[0-9a-f]{2}', '', text)
    return re.sub(r'\s+', ' ', text).strip()


def _strip_version_parts(text):
    """Clean version/part identifiers: 's12', 'v1.2', 'v.4', '.001'."""
    text = re.sub(r'\bv\.?\d+(\.\d+)*\b', '', text)
    text = re.sub(r'\bs\d+\b', '', text)
    text = re.sub(r'\.\d{3,}\b', '', text)  # .001 suffixes
    return re.sub(r'\s+', ' ', text).strip()


def _strip_scene_project_names(text):
    """Remove scene/project name patterns that are NOT object descriptions."""
    # 'blender 3.3 splash' -> ''
    text = re.sub(r'\bblender\s+\d+\.\d+\s+splash\b', '', text, flags=re.I)
    # 'blender swap' or 'blenderswap'
    text = re.sub(r'\bblender\s*swap\b', '', text, flags=re.I)
    # 'splash pokedstudio' style
    text = re.sub(r'\bsplash\s+\w+studio\b', '', text, flags=re.I)
    # 'studio,' prefix for Italian models
    text = re.sub(r'\boggetti\s+studio\b', '', text, flags=re.I)
    # 'cycles,' suffix (render engine name)
    text = re.sub(r'\bcycles\b', '', text, flags=re.I)
    # Scene description patterns like 'lone monk and exposure node demo'
    text = re.sub(r'\b\w+\s+(?:and\s+)?(?:exposure|node|demo|setup|test|sample|example)\s*(?:\w+\s*)*\b(?=\s|$)', '', text, flags=re.I)
    # 'by AuthorName' credits
    text = re.sub(r'\bby\s+\w+\b', '', text, flags=re.I)
    # Project/author prefixes we've seen
    for name in ('lone monk', 'exposure node demo', 'node demo',
                 'archiviz', 'hair nodes', 'ik rig', 'lp',
                 'stylized levi', 'exhibition', 'final',
                 'water 0.99', 'optimized', 'sunna koji2ug',
                 'the white room jay hardy', 'hennessey gt',
                 'augalas', 'dono maison', 'humphh',
                 'warpglow', 'hullgrey', 'hullgraydark',
                 'neroluc', 'plast nera'):
        text = re.sub(r'\b' + re.escape(name) + r'\b', '', text, flags=re.I)
    # Franchise / universe noise that sneaks in from Objaverse metadata
    # e.g. "sd macross sdf 1 macross launch! characters creatures" → discard
    franchise_words = frozenset({
        'macross', 'gundam', 'evangelion', 'pokemon', 'minecraft',
        'fortnite', 'warcraft', 'starcraft', 'hearthstone', 'overwatch',
        'halflife', 'tf2', 'counterstrike', 'valorant', 'skyrim',
        'oblivion', 'fallout', 'diablo', 'warframe', 'dota', 'league',
    })
    words = text.lower().split()
    franchise_hits = sum(1 for w in words if w in franchise_words)
    if franchise_hits >= 2 or (franchise_hits == 1 and len(words) <= 4):
        # Label heavily dominated by franchise names — discard
        return ''
    return re.sub(r'\s+', ' ', text).strip()


def _is_material_only_label(label: str) -> bool:
    """Return True if label consists entirely of material/color words.
    
    Labels like "metal", "wood dry", "grey stone" describe surface properties,
    not what the 3D object IS.  These poison text→geometry alignment because
    the model learns that any mesh can be "metal".
    """
    if not label:
        return True
    words = re.split(r'[\s,]+', label.lower().strip())
    words = [w for w in words if w]
    if not words:
        return True
    meaningful = [w for w in words if w not in _MATERIAL_ONLY_WORDS]
    return len(meaningful) == 0


def _is_low_quality_label(label: str) -> bool:
    """Return True if label should be discarded as low-quality.

    Catches patterns that slip through individual cleaners:
    - Overly long run-on strings that are scene/file descriptions
    - Labels made of mostly exclamation marks / punctuation
    - Labels with >6 comma-separated tokens (tag-dump from metadata)
    - Labels consisting entirely of material/color words
    """
    if not label:
        return True
    # Too many words → likely file/scene description, not a mesh prompt
    words = label.split()
    if len(words) > 10:
        return True
    # Tag dumps: more than 3 comma-separated segments.
    # Real object labels use spaces, not commas.
    # "medieval sword" = good.  "sword, bouncing, candy" = tag soup.
    # Threshold 3 keeps "plank, wood" (1 comma) while catching
    # "sword, bouncing, candy, metal" (3 commas).
    if label.count(',') >= 3:
        return True
    # Pure punctuation / symbol garbage
    alnum = re.sub(r'[^a-z0-9]', '', label.lower())
    if len(alnum) < 3:
        return True
    # Digits dominate (version numbers, IDs)
    # Threshold 0.5 lets through valid model names like "colt m1911"
    # (4 digits / 9 chars = 0.44) while still catching mostly-numeric junk.
    digit_ratio = sum(c.isdigit() for c in alnum) / max(len(alnum), 1)
    if digit_ratio > 0.5:
        return True
    # Material-only labels (e.g. "metal", "wood dry", "grey")
    if _is_material_only_label(label):
        return True
    return False


def _strip_number_suffixes(text):
    """Remove trailing numbers that are just part IDs: 'hair2', 'leaves1'."""
    # 'hair2' -> 'hair', but keep 'ps4' or '3d'
    text = re.sub(r'(\b[a-z]{3,})\d+\b', r'\1', text)
    return text.strip()


def _clean_label_final(label):
    """Master cleaning pipeline — all passes in order."""
    if not label:
        return ''

    label = label.lower()
    label = label.replace('_', ' ').replace('-', ' ')

    # Structural cleaning
    label = _strip_encoding_artifacts(label)
    label = _strip_numeric_ids(label)
    label = _strip_hex_uids(label)
    label = _strip_blender_prefixes(label)
    label = _strip_version_parts(label)
    label = _strip_scene_project_names(label)
    label = _strip_number_suffixes(label)

    # Translate foreign words AFTER structural cleaning
    label = _translate_foreign(label)

    # Strip behavioral/animation words that describe motion, not shape.
    # "bouncing monkey" → "monkey", "animated spinning top" → "spinning top"
    # ("spinning top" is the object name, "spinning" alone would be stripped)
    _BEHAVIORAL_PREFIXES = {
        'animated', 'bouncing', 'dancing', 'falling', 'floating',
        'flying', 'idle', 'looping', 'rigged', 'rolling', 'rotating',
        'running', 'walking', 'wiggling', 'cycling', 'posing',
        'jumpers', 'spawning', 'spawn',
    }
    words = label.split()
    # Only strip if the behavioral word is a prefix AND something remains
    if len(words) > 1 and words[0] in _BEHAVIORAL_PREFIXES:
        label = ' '.join(words[1:])

    # Remove parenthetical detail markers (added back by rebuild_cache)
    label = re.sub(r'\s*\((?:detailed|high-detail)\)\s*', '', label)

    # Remove redundant punctuation and whitespace
    label = re.sub(r'[,\s]{2,}', ', ', label)
    label = re.sub(r'\s+', ' ', label)
    label = label.strip(' ,.:;')

    # Remove words that are just single letters or digits
    words = label.split()
    words = [w for w in words if len(w) > 1 or w in ('a',)]
    label = ' '.join(words)

    if len(label) < 2:
        return ''

    return label


