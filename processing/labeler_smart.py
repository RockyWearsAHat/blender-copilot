def _is_primitive_name(name):
    """True if name is just a bare Blender primitive (possibly with .001)."""
    clean = re.sub(r'\.\d+$', '', name.lower().strip())
    clean = clean.replace('_', '').replace('-', '').replace(' ', '')
    return clean in _PRIMITIVE_NAMES


def _contextualize_primitive(prim_name, material_names=None,
                             file_label="", sibling_names=None):
    """Build a contextual label for a primitive-named object.

    Instead of labeling "Cube.007" as just "cube", we look at what
    surrounds it:
      - Material tells us WHAT it is: mat='Hair' → 'hair'
      - File label gives scene context: file='elastic_deform_snake_hook' → 'snake hook'
      - Sibling names tell us what else is in the scene

    Returns a descriptive label or '' if no context available.
    """
    # Clean the primitive type (cube, cylinder, bezier curve, etc.)
    prim_clean = re.sub(r'\.\d+$', '', prim_name.lower().strip())
    prim_clean = prim_clean.replace('_', ' ').replace('-', ' ')
    # Normalize compound names: 'beziercurve' → 'bezier curve'
    prim_clean = re.sub(r'(bezier)(curve|circle)', r'\1 \2', prim_clean)
    prim_clean = re.sub(r'(nurbs)(path|circle)', r'\1 \2', prim_clean)
    prim_clean = re.sub(r'(uv)(sphere)', r'\1 \2', prim_clean)

    # Names that are Blender internals / non-descriptive as sibling context
    _BAD_SIBLING_NAMES = frozenset({
        'camera', 'light', 'lamp', 'sun', 'spot', 'area', 'empty',
        'armature', 'gpencil', 'grease pencil', 'bone', 'rig',
    })

    context_parts = []

    # 1. Material names — can hint at WHAT the object is.
    #    rebuild_cache.py only sends material names from objects with REAL
    #    materials, so we trust everything we receive.
    #    - Identity names ("hair", "umbrella stick") → use alone
    #    - Material-type names ("metal", "chrome") → combine with primitive
    #      type for a descriptive label: "metal cube", "chrome sphere"
    if material_names:
        good_mats = []
        for m in material_names:
            cm = _clean_mat_name(m)
            cm = cm.replace('.', ' ').strip()
            cm = re.sub(r'\s+', ' ', cm)
            if cm and len(cm) > 1:
                good_mats.append(cm)
        if good_mats:
            mat = good_mats[0]
            if _is_material_only_label(mat):
                # Material-type word: "metal cube" > "metal"
                context_parts.append(mat + ' ' + prim_clean)
            else:
                # Identity word: "hair" > "hair cube"
                context_parts.append(mat)

    # 2. Sibling names — other objects reveal the scene.
    #    IMPORTANT: sibling names must NOT replace the label entirely.
    #    A "Cube" in a scene with "Suzanne" is NOT a suzanne — it's a
    #    cube that happens to be near a suzanne.  We skip sibling-only
    #    context because it poisons training: the model learns that a
    #    sphere mesh = "suzanne" just because Suzanne was a neighbor.
    #    Sibling context without the primitive type is misleading.
    #    Instead, we fall through to let other strategies handle it,
    #    or the object gets skipped by the quality gate (which is correct).
    # (Disabled — sibling names caused label contamination.)

    # 3. File label — scene-level context
    if file_label and not context_parts:
        cf = _clean_label_final(file_label)
        if cf and len(cf) > 2 and cf not in _USELESS_NAMES:
            context_parts.append(cf)

    if not context_parts:
        return ''  # No context — caller will fall through to other strategies

    # Build label from semantic context only.
    # Important: do NOT append primitive substrate (cube/cylinder/plane/etc)
    # because that pollutes text->shape semantics for part labels.
    # e.g. prefer "hair" over "hair cube".
    context = context_parts[0]
    return _clean_label_final(context)


def _clean_obj_name(name):
    """Clean a Blender object name into a label-safe string."""
    if not name:
        return ''
    name = re.sub(r'\.\d{3,}$', '', name).strip()
    name = name.lower().replace('_', ' ').replace('-', ' ')
    name = _strip_blender_prefixes(name)
    name = _strip_hex_uids(name)
    name = _strip_version_parts(name)
    name = _strip_number_suffixes(name)
    words = name.split()
    words = [w for w in words if w not in _TECHNICAL_WORDS and w not in _PROJECT_NAMES]
    name = ' '.join(words)
    name = _translate_foreign(name)
    if name in _USELESS_NAMES or re.match(r'^[\d\s]+$', name):
        return ''
    return name.strip()


def _clean_mat_name(mat):
    """Clean a material name for use in labels."""
    if not mat or not isinstance(mat, str):
        return ''
    m = re.sub(r'\.\d{3,}$', '', mat).strip().lower()
    m = m.replace('_', ' ').replace('-', ' ').replace('.', ' ')
    m = _strip_hex_uids(m)
    m = _strip_number_suffixes(m)
    words = m.split()
    words = [w for w in words if w not in _TECHNICAL_WORDS and w not in _PROJECT_NAMES]
    m = ' '.join(words)
    m = _translate_foreign(m)
    if m in _USELESS_MATS or re.match(r'^material\s*\d*$', m):
        return ''
    return m.strip()


def _build_geo_desc(bbox_aspect, num_faces):
    """Build geometry descriptors from bounding box and face count."""
    parts = []
    if bbox_aspect is not None:
        w, d, h = bbox_aspect
        max_dim = max(w, d, h)
        min_dim = min(w, d, h) + 0.001
        ratio = max_dim / min_dim
        if ratio > 4:
            if h > w and h > d:
                parts.append('tall')
            elif w > h * 2 and d > h * 2:
                parts.append('flat')
            else:
                parts.append('elongated')
        elif ratio < 1.5:
            if num_faces < 50:
                parts.append('simple')
    if not parts:
        if num_faces < 20:
            parts.append('simple')
        elif num_faces > 1000:
            parts.append('detailed')
    return parts


def generate_smart_label(obj_name="", material_names=None, modifier_types=None,
                         num_faces=0, num_verts=0, bbox_aspect=None,
                         file_label="", metadata_name="",
                         metadata_desc="", metadata_tags=None,
                         metadata_categories=None, sibling_names=None):
    """Generate a descriptive single-object label from all available info.

    Returns a natural-language label (max 100 chars) suitable as a
    text-to-mesh prompt.

    ``sibling_names`` is a list of OTHER object names in the same file,
    used to contextualise bare-primitive names like 'Cube.007'.
    """

    clean_obj = _clean_obj_name(obj_name)
    clean_mats = [m for m in (_clean_mat_name(n) for n in (material_names or [])) if m]
    geo_desc = _build_geo_desc(bbox_aspect, num_faces)

    # Clean file label
    clean_file = ''
    if file_label:
        clean_file = _clean_label_final(file_label)
        if clean_file in _USELESS_NAMES or re.match(r'^[\d\s]+$', clean_file):
            clean_file = ''

    # ── Strategy 0: Primitive with context ──
    # Objects named 'Cube.007', 'Plane.012', 'BezierCurve' etc. need
    # enrichment from materials / siblings / file to be useful labels.
    if _is_primitive_name(obj_name):
        ctx_label = _contextualize_primitive(
            obj_name,
            material_names=material_names,
            file_label=file_label,
            sibling_names=sibling_names,
        )
        if ctx_label and len(ctx_label) > 2:
            return ctx_label[:100]
        # No context found — fall through to remaining strategies

    # ── Strategy 1: Rich Objaverse metadata ──
    if metadata_name and metadata_name.lower().strip() not in _USELESS_NAMES:
        label = _clean_label_final(metadata_name)
        if label and len(label) > 2 and not _is_low_quality_label(label):
            # Only append tags that describe PHYSICAL properties of the
            # object (material, category, shape).  Skip behavioral,
            # animation, platform, and abstract/mood tags — these describe
            # the project, not the mesh.
            if metadata_tags and len(label.split()) < 4:
                useful_tags = []
                for t in (metadata_tags or [])[:5]:
                    tag = t if isinstance(t, str) else t.get('name', '')
                    tag = tag.strip().lower()
                    if (tag and tag not in _SKIP_TAGS
                            and tag in _PHYSICAL_TAGS
                            and tag not in label):
                        useful_tags.append(tag)
                if useful_tags:
                    # Use space, not comma — build a description, not a tag list
                    label = label + ' ' + ' '.join(useful_tags[:2])
            candidate = label.strip()[:100]
            if not _is_low_quality_label(candidate):
                return candidate

    # ── Strategy 2: Object name + file context ──
    if clean_obj and len(clean_obj) > 2:
        # Combine with file label for context if they differ
        if clean_file and clean_file != clean_obj and clean_file not in clean_obj:
            # File gives scene context, obj gives specific part
            # e.g. file='country kitchen', obj='table cross' -> 'kitchen table cross piece'
            label = _clean_label_final(clean_file + ' ' + clean_obj)
        else:
            label = clean_obj
        # Append ONE material if it adds descriptive info (color/material type).
        # Material suffixes are fine — they're real data if the mesh keeps its materials.
        if clean_mats and clean_mats[0] not in label:
            mat = clean_mats[0]
            if len(mat) > 2 and not mat.startswith(label.split()[0]):
                label = label + ', ' + mat
        if label and len(label) > 2 and not _is_low_quality_label(label):
            return _clean_label_final(label)[:100]

    # ── Strategy 3: File label alone (single-object files) ──
    if clean_file and len(clean_file) > 2 and not _is_low_quality_label(clean_file):
        label = clean_file
        if clean_mats and clean_mats[0] not in label:
            label = label + ', ' + clean_mats[0]
        candidate = _clean_label_final(label)[:100]
        if not _is_low_quality_label(candidate):
            return candidate

    # ── Strategy 4: Material-based description ──
    # rebuild_cache.py only sends real material names, so trust them.
    # _is_low_quality_label() still catches pure-material standalone labels.
    if clean_mats:
        good_mats = [m for m in clean_mats if len(m) > 2][:2]
        if good_mats:
            desc = ' '.join(geo_desc) + ' ' if geo_desc else ''
            candidate = _clean_label_final(desc + ', '.join(good_mats))[:100]
            if candidate and not _is_low_quality_label(candidate):
                return candidate

    # ── Strategy 5: Pure geometry (last resort) ──
    # Return empty string so the caller knows we couldn't generate a real label.
    # The caller (rebuild_cache) will skip items with empty/weak labels.
    return ''
